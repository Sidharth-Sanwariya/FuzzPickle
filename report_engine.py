def build_report(json_path, output_path, scan_id):
    with open(json_path, "r") as f:
        results = json.load(f)

    report = []
    report.append(f"# FuzzPickle Security Audit Report\n")
    report.append(f"**Scan ID:** `{scan_id}`\n")
    report.append("This report was generated by FuzzPickle.\n")
    
    is_attack = len(results) > 0 and "technique" in results[0]
    
    if is_attack:
        report.append("## 🚨 Attack Arsenal Summary\n")
        report.append("This report tests specific real-world attack techniques against the scanners.\n")
        
        report.append("| Attack Technique | File Scanned | PickleScan | ModelScan | Fickling | Status |\n")
        report.append("| :--- | :--- | :--- | :--- | :--- | :--- |\n")
        
        bypass_count = 0
        intel_list = []
        
        for res in results:
            technique = res.get('technique', 'Unknown')
            file_scanned = res.get('file_scanned', 'Unknown')
            ps = res.get('picklescan', 'N/A')
            ms = res.get('modelscan', 'N/A')
            fk = res.get('fickling', 'N/A')
            proof = res.get('execution_proof', 'NOT_EXECUTED')
            
            # NEW LOGIC: Check if ALL scanners missed it
            all_missed = (ps != "DANGEROUS" and ms != "DANGEROUS" and fk != "DANGEROUS")
            
            results_str = f"{ps} {ms} {fk}".upper()
            has_bypass = "SAFE" in results_str or "BYPASSED" in results_str
            has_crash = "CRASH" in results_str

            if has_bypass:
                if proof == "EXECUTED":
                    if all_missed:
                        status = "☠️ FULL BLIND SPOT (All Missed)"
                    else:
                        status = "🔴 CRITICAL BYPASS"
                    bypass_count += 1
                else:
                    if all_missed:
                        status = "🚨 FULL BLIND SPOT (Unverified)"
                    else:
                        status = "🟠 POTENTIAL BYPASS"
            elif has_crash:
                status = "🟡 AVAILABILITY BUG"
            else:
                status = "✅ Caught"
                
            report.append(f"| `{technique}` | `{file_scanned}` | {ps} | {ms} | {fk} | {status} |\n")
            
            intel = CVE_INTEL.get(technique, "No known CVE correlation.")
            intel_list.append(f"### {technique}\n{intel}\n")
            
        report.append(f"\n**Verified Bypasses (RCE Confirmed):** {bypass_count} out of {len(results)}\n")
        report.append("\n---\n")
        report.append("## 🧠 Detailed Threat Intelligence\n")
        report.append("\n".join(intel_list))
        
    else:
        report.append("## Executive Summary\n")
        report.append("When scanners miss payloads or silently skip files, malicious models can bypass security checks entirely.\n")
        report.append("## Detailed Findings\n")

        bypass_count = 0
        for res in results:
            file_name = res.get('file', 'Unknown')
            ps = res.get('picklescan', 'N/A')
            ms = res.get('modelscan', 'N/A')
            fk = res.get('fickling', 'N/A')
            proof = res.get('execution_proof', 'NOT_EXECUTED')

            results_str = f"{ps} {ms} {fk}".upper()
            
            if "SAFE" in results_str or "BYPASSED" in results_str or "CRASH" in results_str:
                bypass_count += 1
                report.append(f"### Case {bypass_count}: `{file_name}`\n")
                report.append(f"**Scanner Verdicts:** PickleScan: `{ps}` | ModelScan: `{ms}` | Fickling: `{fk}`\n")
                
                report.append("**Real-World Impact:**")
                if proof == "EXECUTED":
                    report.append("🚨 **CRITICAL: PAYLOAD EXECUTION CONFIRMED.** The scanner missed this file, and the payload successfully executed, proving a real-world RCE vulnerability.")
                elif "SAFE" in results_str:
                    # NEW: Check if ALL scanners missed it
                    all_missed = (ps != "DANGEROUS" and ms != "DANGEROUS" and fk != "DANGEROUS")
                    if all_missed:
                        report.append("☠️ **FULL BLIND SPOT:** PickleScan, ModelScan, and Fickling ALL flagged this file as SAFE. This is a complete failure of the entire scanner stack.")
                    else:
                        report.append("**CRITICAL BLIND SPOT:** One or more scanners flagged this file as SAFE. (Execution not verified).")
                elif "CRASH" in results_str:
                    report.append("**AVAILABILITY BUG:** The scanner crashed. While this may block deployment, it indicates a severe lack of robustness in the scanner's parser.")

    with open(output_path, "w") as f:
        f.write("\n".join(report))
    
    # 2. Generate HTML
    html_path = output_path.replace(".md", ".html")
    try:
        if os.path.exists("template.html"):
            with open("template.html", "r") as f:
                html_template = f.read()
            
            # Inject both the results and the intel
            json_results = json.dumps(results, indent=4)
            json_intel = json.dumps(CVE_INTEL, indent=4)
            
            # We will replace two placeholders now: __DATA__ and __INTEL__
            html_content = html_template.replace("__DATA__", json_results)
            html_content = html_content.replace("__INTEL__", json_intel)
            
            with open(html_path, "w") as f:
                f.write(html_content)
    except Exception as e:
        print(f"[-] Warning: Could not generate HTML report: {e}")

    return bypass_count
